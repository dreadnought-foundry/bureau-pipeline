DEFAULT_TOKENS_HREF = "console/design/tokens.css"

_PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- Defence in depth behind the mockup allowlist: even a hole in it cannot
     execute, load a frame, or reach a third-party host. The kpi-data block
     below is a JSON DATA island, not a script — browsers never execute it,
     and script-src does not remove it from the DOM. -->
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'none'; object-src 'none'; frame-src 'none'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; base-uri 'none'; form-action 'none'">
<title>{title}</title>
<link rel="stylesheet" href="{tokens}">
<style>
  body {{ margin: 0 auto; max-width: 56rem; padding: 2rem 1.5rem 6rem;
         font-family: var(--font-body, system-ui, sans-serif);
         background: var(--surface, #fff); color: var(--text, #111); }}
  section {{ scroll-margin-top: 2rem; }}
  [data-anchor] {{ position: relative; }}
  [data-anchor] > a.anchor {{ position: absolute; left: -1.25rem; opacity: 0;
         text-decoration: none; }}
  [data-anchor]:hover > a.anchor {{ opacity: .5; }}
  table {{ border-collapse: collapse; width: 100%; }}
  th, td {{ border: 1px solid var(--border, #ddd); padding: .4rem .6rem;
         text-align: left; }}
  .mockup {{ border: 1px solid var(--border, #ddd); border-radius: .5rem;
         padding: 1rem; }}
</style>
</head>
<body>
<h1 id="title">{title}</h1>
{body}
<script type="application/json" id="kpi-data">{kpis}</script>
</body>
</html>
"""


def _esc(text: str) -> str:
    return html.escape(text, quote=False)


def _inline(text: str) -> str:
    """Escape, then re-admit the two inline marks a plan actually uses."""
    out = _esc(text)
    out = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"`(.+?)`", r"<code>\1</code>", out)
    return out


def _table(rows: list[str]) -> str:
    cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
    body = [c for c in cells if not all(set(x) <= set("-: ") and x for x in c)]
    if not body:
        return ""
    head, rest = body[0], body[1:]
    out = ["<table>", "<thead><tr>"
           + "".join(f"<th>{_inline(c)}</th>" for c in head)
           + "</tr></thead>", "<tbody>"]
    for row in rest:
        out.append("<tr>" + "".join(f"<td>{_inline(c)}</td>" for c in row) + "</tr>")
    out += ["</tbody>", "</table>"]
    return "\n".join(out)


def _render_section(key: str, body: str) -> str:
    """One section: an anchored <section>, and an anchored id per paragraph.

    Paragraph ids are numbered WITHIN the section, so editing the business
    case does not renumber the anchors a comment on the outcome is bound to.
    """
    anchor = key.replace(" ", "-")
    title = section_title(key)
    out = [f'<section id="{anchor}" data-anchor>',
           f'<a class="anchor" href="#{anchor}">#</a>',
           f"<h2>{_esc(title)}</h2>"]
    para = 0
    i = 0
    lines = body.split("\n")
    while i < len(lines):
        line = lines[i]
        if line.startswith("```"):
            lang = line[3:].strip().lower()
            block: list[str] = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                block.append(lines[i])
                i += 1
            i += 1
            raw = "\n".join(block)
            if lang == "mockup":
                # Markup, not escaped text: this IS the UI, and a picture of
                # it would be the thing this card exists to replace. Through
                # the allowlist first — "live" means styled by real tokens,
                # never executing (see _MOCKUP_ALLOWED_TAGS).
                safe, _removed = sanitize_mockup(raw)
                out.append(f'<div class="mockup" id="{anchor}-mockup" '
                           f'data-anchor>'
                           f'<a class="anchor" href="#{anchor}-mockup">#</a>'
                           f"\n{safe}\n</div>")
            elif lang == "kpis":
                out.append(_kpi_table(raw, anchor))
            else:
                out.append(f"<pre><code>{_esc(raw)}</code></pre>")
            continue
        if line.strip().startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append(lines[i])
                i += 1
            out.append(_table(rows))
            continue
        if re.match(r"^\s*[-*]\s+", line):
            items = []
            while i < len(lines) and re.match(r"^\s*[-*]\s+", lines[i]):
                items.append(re.sub(r"^\s*[-*]\s+", "", lines[i]))
                i += 1
            out.append("<ul>" + "".join(f"<li>{_inline(x)}</li>" for x in items)
                       + "</ul>")
            continue
        if line.startswith("#"):
            out.append(f"<h3>{_inline(line.lstrip('#').strip())}</h3>")
            i += 1
            continue
        if not line.strip():
            i += 1
            continue
        chunk = []
        while i < len(lines) and lines[i].strip() and not lines[i].startswith(
                ("```", "#")) and not lines[i].strip().startswith("|") \
                and not re.match(r"^\s*[-*]\s+", lines[i]):
            chunk.append(lines[i].strip())
            i += 1
        para += 1
        pid = f"{anchor}-p{para}"
        out.append(f'<p id="{pid}" data-anchor>'
                   f'<a class="anchor" href="#{pid}">#</a>'
                   f"{_inline(' '.join(chunk))}</p>")
    out.append("</section>")
    return "\n".join(out)


def _kpi_table(raw: str, anchor: str) -> str:
    try:
        records = json.loads(raw)
    except json.JSONDecodeError:
        return f"<pre><code>{_esc(raw)}</code></pre>"
    cols = ["name", "baseline", "unit", "direction", "target"]
    out = [f'<table id="{anchor}-table"><thead><tr>'
           + "".join(f"<th>{c}</th>" for c in cols) + "</tr></thead><tbody>"]
    for k in records:
        if not isinstance(k, dict):
            continue
        out.append("<tr>" + "".join(
            f"<td>{_esc(str(k.get(c, '')))}</td>" for c in cols) + "</tr>")
    out.append("</tbody></table>")
    return "\n".join(out)


def render(md: str, epic: str, tokens_href: str | None = None) -> str:
    """plan.html — the build output. The planner writes markdown; the run
    produces this, so the artifact is an output rather than a capability."""
    found = sections(md)
    title_m = re.search(r"^#\s+(?P<t>.+)$", md, re.MULTILINE)
    title = title_m.group("t").strip() if title_m else epic
    order = [VERSION_RECORD] + REQUIRED_SECTIONS
    body = "\n".join(_render_section(k, found[k]) for k in order if k in found)
    try:
        payload = json.dumps(kpis(md))
    except ArtifactError:
        payload = "[]"
    return _PAGE.format(
        title=_esc(f"{epic} — {title}" if epic and epic not in title else title),
        tokens=_esc(tokens_href or DEFAULT_TOKENS_HREF),
        body=body,
        kpis=payload.replace("</", "<\\/"),
    )


# --- CLI ---------------------------------------------------------------------


def _read(path: str) -> str:
    try:
        with open(path, encoding="utf-8") as f:
            return f.read()
    except OSError as e:
        raise ArtifactError(f"cannot read artifact {path}: {e.strerror}") from e


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("check", help="every reason this artifact is not fit")
    c.add_argument("artifact")
    c.add_argument("--ui", action="store_true",
                   help="this epic builds UI: a live mockup is mandatory")

    k = sub.add_parser("kpis", help="the predictions, as JSON")
    k.add_argument("artifact")

    r = sub.add_parser("render", help="write plan.html")
    r.add_argument("artifact")
    r.add_argument("--epic", required=True)
    r.add_argument("-o", "--out", required=True)
    r.add_argument("--tokens", default=None)

    u = sub.add_parser("url", help="the stable URL, or nothing")
    u.add_argument("epic")
    u.add_argument("--base", default=os.environ.get("PLAN_PORTAL_BASE_URL", ""))

    pa = sub.add_parser("path", help="the stable path under the portal")
    pa.add_argument("epic")

    p = sub.add_parser("publish", help="write the page + source into a portal")
    p.add_argument("artifact")
    p.add_argument("--epic", required=True)
    p.add_argument("--portal", required=True)
    p.add_argument("--base", default=os.environ.get("PLAN_PORTAL_BASE_URL", ""))
    p.add_argument("--tokens", default=None)

    v = sub.add_parser("version-record",
                       help="what changed since the published version")
    v.add_argument("artifact")
    v.add_argument("--epic", required=True)
    v.add_argument("--portal", required=True)

    w = sub.add_parser("with-version-record",
                       help="fold a generated record into the artifact")
    w.add_argument("artifact")
    w.add_argument("record")
    w.add_argument("-o", "--out", required=True)

    sub.add_parser("ui-epic",
                   help="read child card bodies on stdin; true if UI work")

    co = sub.add_parser("closeout", help="prediction vs outcome, as JSON")
    co.add_argument("artifact")
    co.add_argument("outcomes")

    args = ap.parse_args(argv)

    if args.cmd == "ui-epic":
        print("true" if is_ui_epic(sys.stdin.read()) else "false")
        return 0
    if args.cmd == "path":
        print(stable_path(args.epic))
        return 0
    if args.cmd == "url":
        url = stable_url(args.epic, args.base)
        if url:
            print(url)
        return 0

    if args.cmd == "check":
        found = defects(_read(args.artifact), ui=args.ui)
        if not found:
            print("plan artifact: complete")
            return 0
        print(f"plan artifact: {len(found)} defect(s)", file=sys.stderr)
        for d in found:
            print(f"  - {d}", file=sys.stderr)
        return 1

    if args.cmd == "kpis":
        print(json.dumps(kpis(_read(args.artifact)), indent=2))
        return 0

    if args.cmd == "render":
        out = render(_read(args.artifact), args.epic, tokens_href=args.tokens)
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(out)
        print(args.out)
        return 0

    if args.cmd == "publish":
        page = publish(_read(args.artifact), args.epic, args.portal,
                       tokens_href=args.tokens)
        url = stable_url(args.epic, args.base)
        print(url or page)
        return 0

    if args.cmd == "version-record":
        previous = published_source(args.portal, args.epic)
        if previous is None:
            return 0  # revision one: nothing to diff, and none invented
        sys.stdout.write(version_record(previous, _read(args.artifact)))
        return 0

    if args.cmd == "with-version-record":
        merged = with_version_record(_read(args.artifact), _read(args.record))
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(merged)
        print(args.out)
        return 0

    if args.cmd == "closeout":
        outcomes = json.loads(_read(args.outcomes))
        print(json.dumps(closeout(_read(args.artifact), outcomes), indent=2))
        return 0

    return 2


if __name__ == "__main__":
    try:
        raise SystemExit(main(sys.argv[1:]))
    except ArtifactError as e:
        # The only abort: explicit, at top level, CLI-only — a malformed
        # artifact is a finding for the planner, never a traceback.
        raise SystemExit(f"plan artifact: {e}")
