class Replay:
    def __init__(self, use_real_receipt: bool, with_note: bool = True):
        #: False = the CONTROL: the card as it really was (the medic's old
        #: rate-limit literal, no evidence note).
        self.with_note = with_note
        #: variant B feeds the REAL 15:47 PT re-dispatch receipt; variant A
        #: leaves it out because its own 15:46 sweep writes one.
        self.use_real_receipt = use_real_receipt
        self.posted_pr: list[dict] = []     # what the replayed sweeps posted
        self.posted_card: list[tuple[str, str]] = []  # (createdAt, body)
        self.note_at, self.note = evidence_note()
        self.now = ""
        self.calls: list[list[str]] = []

    # --- state as of `now` --------------------------------------------------
    def pr_comments(self) -> list[dict]:
        real = [
            {"author": c["author"], "body": c["body"], "createdAt": c["createdAt"]}
            for c in REAL_COMMENTS
            if c["createdAt"] < self.now
            and (self.use_real_receipt or c is not REAL_REDISPATCH_RECEIPT)
        ]
        return sorted(real + self.posted_pr, key=lambda c: c["createdAt"])

    def listing(self) -> list[dict]:
        return [{
            "number": PR_NUMBER,
            "headRefName": PR["headRefName"],
            "headRefOid": CRASHED_HEAD,      # the head at the time (captured commits)
            "baseRefName": PR["baseRefName"],
            "mergeStateStatus": "CLEAN",     # SYNTHESIZED — not recoverable today
            "isDraft": False,
            "comments": self.pr_comments(),
        }]

    def card_bodies(self, identifier: str) -> list[str]:
        assert identifier == CARD, identifier
        rows = []
        for c in LINEAR:
            if c["createdAt"] >= self.now or c["id"] == REAL_REVIEWER_DOWN_ID:
                continue
            body = (self.note if self.with_note and c["id"] == REAL_MEDIC_LITERAL_ID
                    else c["body"])
            rows.append((c["createdAt"], body))
        rows += [r for r in self.posted_card]
        return [b for _, b in sorted(rows)]

    # --- the fake `gh` -------------------------------------------------------
    def _stamp(self) -> str:
        at = _t(self.now) + timedelta(seconds=45 + len(self.posted_pr))
        return at.strftime("%Y-%m-%dT%H:%M:%SZ")

    def run(self, argv, **_kw):
        assert argv[0] == "gh", f"unexpected process: {argv}"
        self.calls.append(list(argv))
        ok = lambda out="": SimpleNamespace(returncode=0, stdout=out, stderr="")  # noqa: E731
        if argv[1:3] == ["pr", "list"]:
            return ok(json.dumps(self.listing()))
        if argv[1] == "api" and f"/commits/{CRASHED_HEAD}/check-runs" in argv[2]:
            return ok(review_checks_at(self.now))
        if argv[1] == "api" and ("/compare/" in argv[2] or "/commits?" in argv[2]):
            return ok("")  # unreadable, as the test harness answers: no content carry
        if argv[1:3] == ["run", "list"]:
            return ok(json.dumps(dispatch_runs_at(self.now)))
        if argv[1:3] == ["workflow", "run"]:
            return ok()  # RECORDED in self.calls; nothing is dispatched
        if argv[1:3] == ["pr", "comment"]:
            assert argv[3] == str(PR_NUMBER)
            self.posted_pr.append({
                "author": {"login": "agent-bureau-bot"},
                "body": argv[argv.index("--body") + 1],
                "createdAt": self._stamp(),
            })
            return ok()
        raise AssertionError(f"the replay has no answer for: {argv}")

    def card_comment(self, identifier, body):
        assert identifier == CARD, identifier
        self.posted_card.append((self._stamp(), body))

    # --- one sweep -----------------------------------------------------------
    def sweep(self, now: str) -> dict:
        self.now = now
        reconcile.reset_sweep_cards()
        reconcile._write_failures.clear()
        reconcile._read_failures.clear()
        renv.POST_FAILURES.clear()
        before = (len(self.calls), len(self.posted_pr), len(self.posted_card))
        checks, runs = review_checks_at(now), dispatch_runs_at(now)

        def no_network(*_a, **_k):
            raise AssertionError("the replay is offline — a socket was opened")

        log = io.StringIO()
        with patch.object(reconcile.subprocess, "run", side_effect=self.run), \
                patch.object(renv.subprocess, "run", side_effect=self.run), \
                patch.object(socket, "create_connection", side_effect=no_network), \
                patch.object(socket.socket, "connect", side_effect=no_network), \
                patch.object(reconcile.linear_ops, "comment_bodies",
                             side_effect=self.card_bodies), \
                patch.object(reconcile.linear_ops, "cmd_comment",
                             side_effect=self.card_comment), \
                contextlib.redirect_stdout(log), contextlib.redirect_stderr(log):
            reconcile.recover_crashed_reviews()
        calls = self.calls[before[0]:]
        return {
            "simulated_time_utc": now,
            "simulated_time_pt": _pt(now),
            "review_checks_at_head": json.loads(checks),
            "dispatch_runs": runs,
            "pr_thread_size_fed": len(self.pr_comments()) - (len(self.posted_pr) - before[1]),
            "dispatched": [c for c in calls if c[1:3] == ["workflow", "run"]],
            "pr_receipts_posted": [c["body"] for c in self.posted_pr[before[1]:]],
            "card_comments_posted": [b for _, b in self.posted_card[before[2]:]],
            "write_failures": list(reconcile._write_failures),
            "read_failures": list(reconcile._read_failures),
            "sweep_log": log.getvalue().strip().splitlines(),
        }


def _kind(body: str) -> str:
    if renv.HOLD_TAG in body:
        return "HOLD (runner-environment-hold)"
    if reconcile.CRASHED_REVIEW_DISPATCH_TAG in body:
        return "re-dispatch receipt (crashed-review-redispatch)"
    if reconcile.REVIEWER_DOWN_TAG in body:
        return "reviewer-down report"
    return "other"


def drive(use_real_receipt: bool) -> list[dict]:
    world = Replay(use_real_receipt)
    clock = SWEEP_CLOCK[1:] if use_real_receipt else SWEEP_CLOCK
    rows = []
    for at, reconcile_run in clock:
        row = world.sweep(at)
        row["real_reconcile_run_id"] = reconcile_run
        rows.append(row)
    return rows


