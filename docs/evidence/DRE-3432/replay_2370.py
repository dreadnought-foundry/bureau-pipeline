def _t(iso: str) -> datetime:
    return datetime.fromisoformat(iso.replace("Z", "+00:00"))


def _pt(iso: str) -> str:
    return _t(iso).astimezone(PT).strftime("%Y-%m-%d %H:%M:%S PT")


