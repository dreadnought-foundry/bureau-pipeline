    real_down = next(c["body"] for c in LINEAR if c["id"] == REAL_REVIEWER_DOWN_ID)
    control_same = control["card_comments_posted"] == [real_down]
    result["control_without_note"] = control
    result["control_reviewer_down_identical_to_real_comment"] = control_same
    print(f"CONTROL: without the evidence note the 16:04 PT sweep dispatched "
          f"{len(control['dispatched'])}, posted {len(control['pr_receipts_posted'])} PR receipt(s) and "
          f"{[_kind(b) for b in control['card_comments_posted']]} on the card — byte-identical to the "
          f"real reviewer-down comment of {_pt('2026-09-08T23:04:47Z')}: {control_same}")
    result["criterion"] = verdicts
    if args.json:
        Path(args.json).write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n",
                                   encoding="utf-8")
        print(f"\nfull result → {args.json}")
    return 0 if all(verdicts.values()) else 1


