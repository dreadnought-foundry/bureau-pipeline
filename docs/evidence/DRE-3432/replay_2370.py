def crash_facts():
    """Each crash, named off the captured records, with the REAL detector and
    the REAL medic classifier run over its REAL log."""
    out = []
    for label, run_id, attempt, job_id in CRASHES:
        jobs = _load(f"qa-review-run-{run_id}-attempt{attempt}-jobs.json")["jobs"]
        run = _load(f"qa-review-run-{run_id}-attempt{attempt}.json")
        job = next(j for j in jobs if j["id"] == job_id)
        failed = next(s for s in job["steps"] if s["conclusion"] == "failure")
        log = (FX / f"job-{job_id}.log").read_text(encoding="utf-8", errors="replace")
        signature = renv.detect(log)
        out.append({
            "label": label, "run_id": run_id, "attempt": attempt,
            "job_id": job_id, "event": run["event"],
            "triggered_by": (run.get("triggering_actor") or {}).get("login"),
            "run_started": _pt(run["run_started_at"]),
            "failed_step": failed["name"],
            "failed_at": _pt(failed["started_at"]),
            "job_completed": _pt(job["completed_at"]),
            "signature": signature.slug if signature else None,
            "medic_class": medic_classify.classify(run["name"], log),
            "run_url": run["html_url"],
        })
    return out


def evidence_note() -> tuple[str, str]:
    """The medic's evidence note for crash 1, GENERATED: the real detector over
    the real log names the signature, and the real writer composes the note
    with the real head sha and the real run URL — the three things medic.yml's
    `backoff` job passes to `reviewer_environment.py note`. Placed at the
    moment the medic REALLY left its (old, rate-limit) note on the card."""
    log = (FX / "job-102264152565.log").read_text(encoding="utf-8", errors="replace")
    signature = renv.detect(log)
    assert signature is not None, "crash 1's real log carries no environment signature"
    run = _load("qa-review-run-34286800645-attempt1.json")
    assert run["head_sha"] == CRASHED_HEAD
    at = next(c["createdAt"] for c in LINEAR if c["id"] == REAL_MEDIC_LITERAL_ID)
    return at, renv.evidence_note(signature, run["head_sha"], run["html_url"])


